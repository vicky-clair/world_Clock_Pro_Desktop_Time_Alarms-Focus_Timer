// T translates key into specified language, falling back to English.
func T(lang Language, key string) string {
	if dict, ok := messages[lang]; ok {
		if val, exists := dict[key]; exists {
			return val
		}
	}
	// Fallback to English
	if dict, ok := messages[LangEN]; ok {
		if val, exists := dict[key]; exists {
			return val
		}
	}
	return key
}

// FormatDateLocalized formats date based on locale and full/short preference.
func FormatDateLocalized(lang Language, month int, day int, year int, weekday int, full bool) string {
	switch lang {
	case LangZH:
		cnWeekdays := []string{"星期日", "星期一", "星期二", "星期三", "星期四", "星期五", "星期六"}
		w := cnWeekdays[weekday%7]
		if full {
			return w + "，" + itoa(year) + "年" + itoa(month) + "月" + itoa(day) + "日"
		}
		return itoa(year) + "年" + itoa(month) + "月" + itoa(day) + "日 " + w

	case LangJA:
		jaWeekdays := []string{"日曜日", "月曜日", "火曜日", "水曜日", "木曜日", "金曜日", "土曜日"}
		jaShortWeekdays := []string{"日", "月", "火", "水", "木", "金", "土"}
		idx := weekday % 7
		if full {
			return itoa(year) + "年" + itoa(month) + "月" + itoa(day) + "日 (" + jaWeekdays[idx] + ")"
		}
		return itoa(year) + "/" + itoa(month) + "/" + itoa(day) + " (" + jaShortWeekdays[idx] + ")"

	case LangEN:
		fallthrough
	default:
		enWeekdays := []string{"Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"}
		enMonths := []string{"January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"}
		w := enWeekdays[weekday%7]
		m := enMonths[(month-1)%12]
		if full {
			return w + ", " + m + " " + itoa(day) + ", " + itoa(year)
		}
		return w[:3] + ", " + m[:3] + " " + itoa(day) + ", " + itoa(year)
	}
}

func itoa(val int) string {
	if val == 0 {
		return "0"
	}
	neg := false
	if val < 0 {
		neg = true
		val = -val
	}
	var buf [20]byte
	i := len(buf)
	for val > 0 {
		i--
		buf[i] = byte('0' + (val % 10))
		val /= 10
	}
	if neg {
		i--
		buf[i] = '-'
	}
	return string(buf[i:])
}
